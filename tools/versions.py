#!/usr/bin/env python3
"""Write version/<v>/doc/system.yaml for every benchmark version: the base's, with that version's overrides.

A version's system.yaml replaces the base's whole (tests: included), so a copy made by hand drifts as soon as the base changes.
This script is the one place the versions are defined: edit VERSIONS, run it (python3 -I tools/versions.py), then hw-proj gen all.
Each override is a line of the base's system.yaml (its start, exactly) and what it becomes.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, "version", "base", "doc", "system.yaml")

PPU = "  ppu0: {module: ppu}"
TEXLD = "  texld0: {module: texld, params: {TEX_W: 32}}"
TEX0 = "  tex0: {module: tex_bank, params: {DEPTH: 16384, WIDTH: 32}}"
WIDTH = "    data_width: 32"


def slots(n):
    return {PPU: f"  ppu0: {{module: ppu, params: {{SLOTS: {n}}}}}"}


def tex(width):
    return {TEXLD: f"  texld0: {{module: texld, params: {{TEX_W: {width}}}}}",
            TEX0: f"  tex0: {{module: tex_bank, params: {{DEPTH: {16384 * 32 // width}, WIDTH: {width}}}}}",
            WIDTH: f"    data_width: {width}"}


VERSIONS = {
    "slots16": slots(16),
    "slots24": slots(24),
    "tex64": tex(64),
    "tex128": tex(128),
    "slots24-tex64": {**slots(24), **tex(64)},
}


def main():
    base = open(BASE).read().splitlines(keepends=True)
    for name, over in VERSIONS.items():
        out, used = [], set()
        for line in base:
            for start, new in over.items():
                if line.startswith(start):
                    line = new + line[len(start):]          # keep the comment after it
                    used.add(start)
            out.append(line)
        missing = set(over) - used
        if missing:
            sys.exit(f"{name}: no line of the base starts with {sorted(missing)}")
        path = os.path.join(ROOT, "version", name, "doc", "system.yaml")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(f"# GENERATED by tools/versions.py from version/base/doc/system.yaml: edit that script, not this file.\n")
            f.writelines(out)
        print(f"{name}: {len(over)} line(s) differ from base")


if __name__ == "__main__":
    main()
