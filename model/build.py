#!/usr/bin/env python3
"""Build one workload: python3 model/build.py <workload> <out dir>

Writes into <out dir>:
  workload.h      the C arrays the firmware copies into the chip (texture SRAM image, OAM, GIANT)
  expected.bin    the golden frame: 640 x 480 rgb444 values, uint16 little endian, row-major
  expected.json   the golden hit bits (4 words, HIT0..HIT3) and the frame's size
  expected.png    the golden frame, to look at
  tex.bin         the texture SRAM image the firmware loads (the testbench checks tex0 against it)
"""

import json
import os
import struct
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from ppu_model import SCREEN_H, SCREEN_W, render   # noqa: E402
from workloads import WORKLOADS                    # noqa: E402


def write_png(path, pixels):
    """rgb444 rows -> an 8-bit RGB PNG (each 4-bit channel repeated: 0xF -> 0xFF)."""
    raw = bytearray()
    for row in pixels:
        raw.append(0)
        for c in row:
            raw += bytes((((c >> 8) & 15) * 17, ((c >> 4) & 15) * 17, (c & 15) * 17))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", len(pixels[0]), len(pixels), 8, 2, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(bytes(raw), 6)))
        f.write(chunk(b"IEND", b""))


def c_words(words, per_line=8):
    lines = []
    for i in range(0, len(words), per_line):
        lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + per_line]) + ",")
    return "\n".join(lines)


def write_header(path, wl, tex):
    tex_words = list(struct.unpack(f"<{len(tex) // 4}I", tex))
    with open(path, "w") as f:
        f.write(f"// generated by model/build.py from model/workloads.py ({wl.name}): {wl.desc}. Do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define WL_NAME \"{wl.name}\"\n")
        f.write(f"#define WL_GIANT 0x{wl.giant:08x}u\n")
        f.write(f"#define WL_TEX_WORDS {len(tex_words)}u\n\n")
        f.write("// the texture SRAM image from byte 0: the palette (0..511), then the textures\n")
        f.write(f"static const uint32_t wl_tex[{len(tex_words)}] = {{\n{c_words(tex_words)}\n}};\n\n")
        f.write("// OAM: sprite i is words 2i (placement) and 2i+1 (appearance)\n")
        f.write(f"static const uint32_t wl_oam[{len(wl.oam)}] = {{\n{c_words(wl.oam)}\n}};\n")


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in WORKLOADS:
        sys.exit(f"usage: build.py <workload> <out dir>; workloads: {', '.join(WORKLOADS)}")
    name, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)

    wl = WORKLOADS[name]()
    tex = wl.tex_bytes()
    frame = render(wl.oam, wl.giant, tex)

    write_header(os.path.join(out, "workload.h"), wl, tex)
    with open(os.path.join(out, "expected.bin"), "wb") as f:
        for row in frame.pixels:
            f.write(struct.pack(f"<{SCREEN_W}H", *row))
    with open(os.path.join(out, "expected.json"), "w") as f:
        json.dump({"workload": name, "width": SCREEN_W, "height": SCREEN_H, "hit": frame.hit_words(),
                   "hit_sprites": [i for i in range(128) if frame.hits >> i & 1]}, f, indent=1)
    write_png(os.path.join(out, "expected.png"), frame.pixels)
    with open(os.path.join(out, "tex.bin"), "wb") as f:
        f.write(tex)
    print(f"{name}: {len(tex)} texture bytes, {sum(1 for i in range(128) if wl.oam[2 * i] >> 28 & 1)} sprites, "
          f"hits {[i for i in range(128) if frame.hits >> i & 1]} -> {out}")


if __name__ == "__main__":
    main()
